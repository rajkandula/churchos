"use client";

import Link from "next/link";
import { useParams } from "next/navigation";
import { ArrowLeft } from "lucide-react";
import { useEffect, useState } from "react";
import { api } from "@/lib/client-api";
import { formatMoney } from "@/lib/money";
import { PrintButton } from "@/components/PrintButton";
import { Letterhead, PrintStyles } from "../../../Letterhead";
import { formatLongDate, type ChurchInfo, type DonationDto } from "../../../types";

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="grid grid-cols-[9rem_1fr] gap-4 border-b border-slate-100 py-3 text-sm">
      <span className="font-semibold tracking-wide text-slate-500 uppercase">{label}</span>
      <span className="font-medium text-slate-900">{value || "—"}</span>
    </div>
  );
}

export default function ReceiptPrintPage() {
  const { id } = useParams<{ id: string }>();
  const [donation, setDonation] = useState<DonationDto | null>(null);
  const [church, setChurch] = useState<ChurchInfo | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api<{ donation: DonationDto }>(`/api/giving/donations/${id}`)
      .then((d) => setDonation(d.donation))
      .catch((err) =>
        setError(err instanceof Error ? err.message : "Could not load this receipt.")
      );
    api<{ church: ChurchInfo }>("/api/settings/church")
      .then((d) => setChurch(d.church))
      .catch(() => {});
  }, [id]);

  const currency = church?.currency ?? "INR";

  return (
    <div className="animate-fade-up">
      <PrintStyles />
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link
          href="/dashboard/giving"
          className="inline-flex items-center gap-1.5 text-sm font-medium text-slate-500 transition-colors duration-200 hover:text-indigo-600"
        >
          <ArrowLeft className="h-4 w-4" aria-hidden />
          Giving
        </Link>
        <PrintButton />
      </div>

      {error && (
        <div
          role="alert"
          className="mt-4 rounded-xl border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-800 print:hidden"
        >
          {error}
        </div>
      )}

      <article className="mx-auto mt-5 max-w-2xl rounded-2xl border border-slate-200 bg-white p-8 shadow-sm sm:p-10 print:mt-0 print:max-w-none print:rounded-none print:border-0 print:p-0 print:shadow-none">
        <Letterhead church={church} />

        {donation ? (
          <>
            <div className="mt-8 flex flex-wrap items-end justify-between gap-4">
              <div>
                <p className="text-xs font-bold tracking-[0.2em] text-indigo-600 uppercase">
                  Donation receipt
                </p>
                <p className="mt-1 font-mono text-2xl font-bold text-slate-900">
                  {donation.receiptNo}
                </p>
              </div>
              <div className="text-right text-sm">
                <p className="text-xs font-semibold tracking-wide text-slate-500 uppercase">Date</p>
                <p className="font-medium text-slate-900">{formatLongDate(donation.date)}</p>
              </div>
            </div>

            <div className="mt-6">
              <Row label="Received from" value={donation.personName || "Anonymous"} />
              <Row label="Towards" value={donation.fundName} />
              <Row label="Payment mode" value={donation.mode} />
              <Row label="Reference" value={donation.reference} />
              {donation.note && <Row label="Note" value={donation.note} />}
            </div>

            <div className="mt-6 flex items-center justify-between rounded-2xl border border-indigo-100 bg-indigo-50/60 px-6 py-5 print:border-slate-300 print:bg-transparent">
              <span className="text-sm font-semibold tracking-wide text-slate-600 uppercase">
                Amount received
              </span>
              <span className="text-3xl font-bold text-slate-900 tabular-nums">
                {formatMoney(donation.amount, currency)}
              </span>
            </div>

            <p className="mt-6 text-sm leading-relaxed text-slate-600">
              Thank you for your generous gift{church ? ` to ${church.name}` : ""}. It is a
              blessing and will be used faithfully for the purpose given.
            </p>

            <div className="mt-14 flex items-end justify-between">
              <p className="text-[11px] text-slate-400">
                Generated by ChurchOS · {formatLongDate(new Date())}
              </p>
              <div className="w-56 text-center">
                <div className="border-t border-slate-400" />
                <p className="mt-2 text-sm font-semibold text-slate-700">Treasurer</p>
              </div>
            </div>
          </>
        ) : (
          !error && (
            <div className="mt-8 space-y-3">
              {[0, 1, 2, 3].map((i) => (
                <div key={i} className="h-4 w-full animate-pulse rounded bg-slate-100" />
              ))}
            </div>
          )
        )}
      </article>
    </div>
  );
}
